/**
 * 工具类别枚举
 * 用于分类和管理不同类型的工具
 */
enum class ToolCategory {
    FILE_SYSTEM,    // 文件系统工具
    NETWORK,        // 网络工具
    SYSTEM,         // 系统工具
    UI_AUTOMATION,  // UI自动化工具
    MEDIA,          // 媒体工具
    AI,             // AI工具
    AUTOMATION,     // 自动化工具
    VOICE,          // 语音工具
    CAMERA,         // 相机工具
    LOCATION,       // 位置工具
    NOTIFICATION    // 通知工具
}